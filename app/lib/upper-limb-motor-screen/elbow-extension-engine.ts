export type ElbowExtensionZone = {
  point: NormalizedPoint;
  radius: number;
};

function isFiniteUnitCoordinate(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && value >= 0 && value <= 1;
}

function isPositiveFiniteRadius(value: unknown): value is number {
  return typeof value === "number" && Number.isFinite(value) && value > 0;
}

type ZoneValidationResult =
  | { ok: true; zone: ElbowExtensionZone }
  | { ok: false; reason: "invalid_zone_geometry"; detail: string };

function validateZone(candidate: unknown, label: string): ZoneValidationResult {
  if (!isRecord(candidate)) {
    return { ok: false, reason: "invalid_zone_geometry", detail: `${label} must be an object` };
  }
  const point = candidate.point;
  if (!isRecord(point) || !isFiniteUnitCoordinate(point.x) || !isFiniteUnitCoordinate(point.y)) {
    return {
      ok: false,
      reason: "invalid_zone_geometry",
      detail: `${label}.point requires finite x and y within [0,1]`,
    };
  }
  if (!isPositiveFiniteRadius(candidate.radius)) {
    return { ok: false, reason: "invalid_zone_geometry", detail: `${label}.radius must be finite and > 0` };
  }
  return { ok: true, zone: { point: { x: point.x, y: point.y }, radius: candidate.radius } };
}

/** Circles touching or overlapping are rejected — a structural geometric rule, not a clinical threshold. */
function zonesOverlapOrTouch(a: ElbowExtensionZone, b: ElbowExtensionZone): boolean {
  return distanceNormalized(a.point, b.point) <= a.radius + b.radius;
}

type UnitDirection2D = { readonly x: number; readonly y: number };

/** Screen-space unit vector from starting zone center toward the fixed target — not anatomical placement. */
function computeNormalizedTargetDirection(
  startingZone: ElbowExtensionZone,
  fixedTarget: ElbowExtensionZone,
): UnitDirection2D | null {
  const dx = fixedTarget.point.x - startingZone.point.x;
  const dy = fixedTarget.point.y - startingZone.point.y;
  const magnitude = Math.hypot(dx, dy);
  if (magnitude === 0) return null;
  return { x: dx / magnitude, y: dy / magnitude };
}

function displacementFromStartCenter(wrist: NormalizedPoint, startCenter: NormalizedPoint): { x: number; y: number } {
  return { x: wrist.x - startCenter.x, y: wrist.y - startCenter.y };
}

function dot2(a: { x: number; y: number }, b: UnitDirection2D): number {
  return a.x * b.x + a.y * b.y;
}

/** Target-facing onset qualification — screen-space projection along configured target direction. */
function hasTargetFacingOnsetQualification(
  wrist: NormalizedPoint,
  startingZone: ElbowExtensionZone,
  normalizedTargetDirection: UnitDirection2D,
): boolean {
  const displacement = displacementFromStartCenter(wrist, startingZone.point);
  return dot2(displacement, normalizedTargetDirection) > startingZone.radius;
}

/** Non-target-facing side exit — screen-space projection opposite configured target direction. */
function hasWrongDirectionExit(
  wrist: NormalizedPoint,
  startingZone: ElbowExtensionZone,
  normalizedTargetDirection: UnitDirection2D,
): boolean {
  const displacement = displacementFromStartCenter(wrist, startingZone.point);
  return dot2(displacement, normalizedTargetDirection) < -startingZone.radius;
}

function cloneElbowExtensionConfig(config: ElbowExtensionConfig): ElbowExtensionConfig {
  return {
    testedSide: config.testedSide,
    fixedTarget: {
      point: { x: config.fixedTarget.point.x, y: config.fixedTarget.point.y },
      radius: config.fixedTarget.radius,
    },
    startingZone: {
      point: { x: config.startingZone.point.x, y: config.startingZone.point.y },
      radius: config.startingZone.radius,
    },
    tracking: {
      minWristVisibility: config.tracking.minWristVisibility,
      maxAllowedGapMs: config.tracking.maxAllowedGapMs,
      minShoulderVisibility: config.tracking.minShoulderVisibility,
      minElbowVisibility: config.tracking.minElbowVisibility,
    },
    timing: {
      onsetConfirmationMs: config.timing.onsetConfirmationMs,
      dwellDurationMs: config.timing.dwellDurationMs,
      returnConfirmationMs: config.timing.returnConfirmationMs,
    },
    normalizedTargetDirection: {
      x: config.normalizedTargetDirection.x,
      y: config.normalizedTargetDirection.y,
    },
  };
}

