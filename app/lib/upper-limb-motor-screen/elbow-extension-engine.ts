// Wrist sample — controls event continuity and protective pauses.
// ---------------------------------------------------------------------------

function extractTestedSideWristSample(
  frame: NormalizedMotionFrame,
  config: ElbowExtensionConfig,
): NormalizedPoint | null {
  const jointId = TESTED_SIDE_WRIST_JOINT_ID[config.testedSide];
  const joint = frame.joints[jointId];
  if (!joint) return null;
  if (!isJointConfident(joint.confidence, config.tracking.minWristVisibility)) return null;
  const { x, y } = joint.landmark;
  if (!isFiniteUnitCoordinate(x) || !isFiniteUnitCoordinate(y)) return null;
  return { x, y };
}

// ---------------------------------------------------------------------------
// Optional 2D elbow-angle observation — never an event gate.
// ---------------------------------------------------------------------------

/**
 * Observed 2D interior angle at the tested-side elbow (shoulder→elbow→wrist).
 * Returns null when any required landmark is missing, out of bounds, or below
 * the configured visibility thresholds. Does not affect wrist-task phases.
 */
export function extractObserved2DElbowAngleDegrees(
  frame: NormalizedMotionFrame,
  config: ElbowExtensionConfig,
): number | null {
  const shoulderId = TESTED_SIDE_SHOULDER_JOINT_ID[config.testedSide];
  const elbowId = TESTED_SIDE_ELBOW_JOINT_ID[config.testedSide];
  const wristId = TESTED_SIDE_WRIST_JOINT_ID[config.testedSide];

  const shoulderJoint = frame.joints[shoulderId];
  const elbowJoint = frame.joints[elbowId];
  const wristJoint = frame.joints[wristId];

  if (!shoulderJoint || !elbowJoint || !wristJoint) return null;

  const { tracking } = config;
  if (
    !isJointConfident(shoulderJoint.confidence, tracking.minShoulderVisibility) ||
    !isJointConfident(elbowJoint.confidence, tracking.minElbowVisibility) ||
    !isJointConfident(wristJoint.confidence, tracking.minWristVisibility)
  ) {
    return null;
  }

  const shoulder = shoulderJoint.landmark;
  const elbow = elbowJoint.landmark;
  const wrist = wristJoint.landmark;

  if (
    !isFiniteUnitCoordinate(shoulder.x) ||
    !isFiniteUnitCoordinate(shoulder.y) ||
    !isFiniteUnitCoordinate(elbow.x) ||
    !isFiniteUnitCoordinate(elbow.y) ||
    !isFiniteUnitCoordinate(wrist.x) ||
    !isFiniteUnitCoordinate(wrist.y)
  ) {
    return null;
  }

  return computeJointAngleDegrees(shoulder, elbow, wrist, {
    confidences: [shoulderJoint.confidence, elbowJoint.confidence, wristJoint.confidence],
    minConfidence: 0,
  });
}

function observePeakElbowAngleIfApplicable(
  state: ElbowExtensionAttemptStateInternal,
  frame: NormalizedMotionFrame,
): ElbowExtensionAttemptStateInternal {
  if (state.phase !== "outbound" && state.phase !== "dwelling") {
    return state;
  }
  const angle = extractObserved2DElbowAngleDegrees(frame, state.config);
  if (angle === null) {
    return state;
  }
  const peak =
    state.peakElbowExtensionDegRunning === null
      ? angle
      : Math.max(state.peakElbowExtensionDegRunning, angle);
  return {
    ...state,
    peakElbowExtensionDegRunning: peak,
    hadValidElbowAngleSample: true,
  };
}

