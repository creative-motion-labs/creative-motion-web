/**
 * RASQ Upper-Limb Motor Screen — Seated Elbow Extension Toward Target and Return.
 *
 * A pure, command-driven reducer. Independent of forward-reach-engine.ts and
 * lateral-reach-engine.ts — no shared module, no imported private logic, no
 * refactor of either reach engine. No UI dependency, no Session Orchestrator
 * dependency, no interactive-shoulder state-machine reuse.
 *
 * Three concerns are kept separate:
 *
 * A. Wrist target-task measurement — movement onset, target entry, dwell,
 *    return, timing, and wrist path metrics. Wrist tracking controls event
 *    continuity and protective pauses.
 *
 * B. Optional factual 2D elbow-angle observation — peakElbowExtensionDeg is
 *    populated only when the tested-side shoulder, elbow, and wrist are
 *    simultaneously valid and confident during outbound/dwelling. Angle
 *    availability never controls wrist-task completion. Shoulder or elbow
 *    loss does not open a protective pause while wrist tracking remains valid.
 *
 * C. Clinician interpretation — never generated by this engine.
 *
 * peakElbowExtensionDeg meaning (Phase 1 contract field, not renamed here):
 * Maximum observed 2D interior angle at the tested-side elbow, computed from
 * shoulder–elbow–wrist landmarks. This is not anatomical ROM, confirmation of
 * full extension, strength, spasticity, or impairment. Target reach is not
 * proof that anatomical elbow extension occurred.
 *
 * Composition only: distanceNormalized/isWristInsideTarget (target-hit.ts),
 * computeJointAngleDegrees/isJointConfident (motion-intelligence),
 * evaluateProtectivePause (protective-pause-evaluator.ts), and Phase 1
 * types/guards (types.ts) are imported read-only.
 *
 * Engine clock: monotonic lastAcceptedNowMs across all command types; frame
 * commands additionally require strictly increasing timestamps
 * (lastAcceptedFrameNowMs). No numeric threshold is hardcoded; every
 * threshold is required explicit configuration marked needs CV validation /
 * needs device testing / needs capture-data calibration below.
 */

