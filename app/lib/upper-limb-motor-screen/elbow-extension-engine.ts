export type ElbowExtensionConfigValidationFailure =
  | "invalid_config"
  | "invalid_tested_side"
  | "invalid_zone_geometry"
  | "zones_overlap"
  | "ambiguous_target_direction"
  | "invalid_tracking_config"
  | "invalid_timing_config";

export type ElbowExtensionConfigValidationResult =
  | { ok: true; config: ElbowExtensionConfig }
  | { ok: false; reason: ElbowExtensionConfigValidationFailure; detail?: string };

function validateVisibilityField(
  value: unknown,
  label: string,
): { ok: true; value: number } | { ok: false; reason: "invalid_tracking_config"; detail: string } {
  if (typeof value !== "number" || !Number.isFinite(value) || value < 0 || value > 1) {
    return {
      ok: false,
      reason: "invalid_tracking_config",
      detail: `${label} must be a finite number within [0,1]`,
    };
  }
  return { ok: true, value };
}

function validateTrackingConfig(
  candidate: unknown,
):
  | { ok: true; tracking: ElbowExtensionTrackingConfig }
  | { ok: false; reason: "invalid_tracking_config"; detail: string } {
  if (!isRecord(candidate)) {
    return { ok: false, reason: "invalid_tracking_config", detail: "tracking config must be an object" };
  }
  const wristVis = validateVisibilityField(candidate.minWristVisibility, "minWristVisibility");
  if (!wristVis.ok) return wristVis;
  const shoulderVis = validateVisibilityField(candidate.minShoulderVisibility, "minShoulderVisibility");
  if (!shoulderVis.ok) return shoulderVis;
  const elbowVis = validateVisibilityField(candidate.minElbowVisibility, "minElbowVisibility");
  if (!elbowVis.ok) return elbowVis;
  if (
    typeof candidate.maxAllowedGapMs !== "number" ||
    !Number.isFinite(candidate.maxAllowedGapMs) ||
    candidate.maxAllowedGapMs < 0
  ) {
    return {
      ok: false,
      reason: "invalid_tracking_config",
      detail: "maxAllowedGapMs must be a finite number >= 0",
    };
  }
  return {
    ok: true,
    tracking: {
      minWristVisibility: wristVis.value,
      maxAllowedGapMs: candidate.maxAllowedGapMs,
      minShoulderVisibility: shoulderVis.value,
      minElbowVisibility: elbowVis.value,
    },
  };
}

function validateTimingConfig(
  candidate: unknown,
): { ok: true; timing: ElbowExtensionTimingConfig } | { ok: false; reason: "invalid_timing_config"; detail: string } {
  if (!isRecord(candidate)) {
    return { ok: false, reason: "invalid_timing_config", detail: "timing config must be an object" };
  }
  const fields = ["onsetConfirmationMs", "dwellDurationMs", "returnConfirmationMs"] as const;
  for (const field of fields) {
    const value = candidate[field];
    if (typeof value !== "number" || !Number.isFinite(value) || value < 0) {
      return {
        ok: false,
        reason: "invalid_timing_config",
        detail: `${field} must be a finite number >= 0`,
      };
    }
  }
  return {
    ok: true,
    timing: {
      onsetConfirmationMs: candidate.onsetConfirmationMs as number,
      dwellDurationMs: candidate.dwellDurationMs as number,
      returnConfirmationMs: candidate.returnConfirmationMs as number,
    },
  };
}

export function validateElbowExtensionConfig(candidate: unknown): ElbowExtensionConfigValidationResult {
  if (!isRecord(candidate)) {
    return { ok: false, reason: "invalid_config", detail: "config must be an object" };
  }

  if (!isValidUpperLimbSide(candidate.testedSide)) {
    return { ok: false, reason: "invalid_tested_side" };
  }
  const testedSide = candidate.testedSide;

  const targetResult = validateZone(candidate.fixedTarget, "fixedTarget");
  if (!targetResult.ok) return targetResult;

  const startingZoneResult = validateZone(candidate.startingZone, "startingZone");
  if (!startingZoneResult.ok) return startingZoneResult;

  if (zonesOverlapOrTouch(targetResult.zone, startingZoneResult.zone)) {
    return { ok: false, reason: "zones_overlap" };
  }

  const normalizedTargetDirection = computeNormalizedTargetDirection(startingZoneResult.zone, targetResult.zone);
  if (normalizedTargetDirection === null) {
    return { ok: false, reason: "ambiguous_target_direction" };
  }

  const trackingResult = validateTrackingConfig(candidate.tracking);
  if (!trackingResult.ok) return trackingResult;

  const timingResult = validateTimingConfig(candidate.timing);
  if (!timingResult.ok) return timingResult;

  return {
    ok: true,
    config: cloneElbowExtensionConfig({
      testedSide,
      fixedTarget: targetResult.zone,
      startingZone: startingZoneResult.zone,
      tracking: trackingResult.tracking,
      timing: timingResult.timing,
      normalizedTargetDirection,
    }),
  };
}

